import { NodePackageManager } from 'projen/lib/javascript';
import { synthSnapshot } from 'projen/lib/util/synth';
import { NpmPackage } from '../../../src/projects/npm';

describe('NPM Package', () => {
  it('synthesizes', () => {
    const project = new NpmPackage({
      codeOwners: ['test'],
      defaultReleaseBranch: 'main',
      name: 'test-npm',
    });

    const output = synthSnapshot(project);

    expect(output.CODEOWNERS).toBeDefined();
    expect(output).toMatchSnapshot();
  });

  it('has readme with project details', () => {
    const project = new NpmPackage({
      autoMerge: false,
      codeOwners: ['test'],
      defaultReleaseBranch: 'main',
      name: 'test-npm',
    });

    const output = synthSnapshot(project);

    expect(output['README.md']).toBe(`<!-- ~~ Generated by projen. To modify, edit .projenrc.ts and run "npx projen". -->

# test-npm

## Getting Started

Prerequisites:
* a current Node.js LTS release
* Yarn 1 (classic)

\`\`\`sh
yarn install
npx projen build
\`\`\``);
  });

  it('has readme with a project description', () => {
    const project = new NpmPackage({
      autoMerge: false,
      codeOwners: ['test'],
      defaultReleaseBranch: 'main',
      name: 'test-npm',
      readme: {
        description: 'A test project description.',
      },
    });

    const output = synthSnapshot(project);

    expect(output['README.md']).toBe(`<!-- ~~ Generated by projen. To modify, edit .projenrc.ts and run "npx projen". -->

# test-npm

A test project description.

## Getting Started

Prerequisites:
* a current Node.js LTS release
* Yarn 1 (classic)

\`\`\`sh
yarn install
npx projen build
\`\`\``);
  });

  it('lists the workflow node version and package manager as prerequisites', () => {
    const project = new NpmPackage({
      codeOwners: ['test'],
      defaultReleaseBranch: 'main',
      name: 'test-npm',
      packageManager: NodePackageManager.NPM,
      workflowNodeVersion: '22.x',
    });

    expect(synthSnapshot(project)['README.md']).toContain(
      'Prerequisites:\n* Node.js 22\n* npm\n\n```sh\nnpm install\n',
    );
  });

  it('type-checks the tests before running them', () => {
    const project = new NpmPackage({
      codeOwners: ['test'],
      defaultReleaseBranch: 'main',
      name: 'test-npm',
    });

    const output = synthSnapshot(project);

    expect(output['.projen/tasks.json'].tasks.test.steps[0]).toEqual({
      name: 'Type-check the test suite',
      execArgs: ['tsc', '--noEmit', '-p', 'test/tsconfig.json'],
    });
  });

  it('can disable type-checking the tests', () => {
    const project = new NpmPackage({
      codeOwners: ['test'],
      defaultReleaseBranch: 'main',
      name: 'test-npm',
      typecheckTests: false,
    });

    const output = synthSnapshot(project);

    expect(output['.projen/tasks.json'].tasks.test.steps).not.toContainEqual(
      expect.objectContaining({ name: 'Type-check the test suite' }),
    );
  });

  it('writes the github configuration guide to the docs directory', () => {
    const project = new NpmPackage({
      codeOwners: ['test'],
      defaultReleaseBranch: 'main',
      name: 'test-npm',
    });

    const output = synthSnapshot(project);

    expect(output['docs/github-configuration.md']).toContain(
      '# GitHub Configuration\n\nAll pull requests are merged by the [Mergify]',
    );
    expect(output['README.md']).toContain(
      '[docs/github-configuration.md](docs/github-configuration.md)',
    );
    expect(output['README.md']).not.toContain('### Branch ruleset');
  });
});
