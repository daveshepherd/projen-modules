import { Project, ProjectOptions, SampleReadme } from 'projen';
import {
  NodePackageManager,
  NodeProject,
  NodeProjectOptions,
} from 'projen/lib/javascript';
import { synthSnapshot } from 'projen/lib/util/synth';
import { Readme, ReadmeOrder } from '../../../src/components/readme';
import { gettingStartedSection } from '../../../src/components/readme/getting-started';

class TestProject extends Project {
  constructor(options: Omit<ProjectOptions, 'name'> = {}) {
    super({
      name: 'my-project',
      ...options,
    });
  }
}

describe('README generation', () => {
  it('has a README with just has project title if nothing else is specified', () => {
    // GIVEN
    const project = new TestProject();

    // WHEN
    new Readme(project);

    // THEN
    const output = synthSnapshot(project)['README.md'];
    expect(output).toEqual(`<!-- ~~ Generated by projen. To modify, edit .projenrc.js and run "npx projen". -->

# my-project\n\n`);
  });

  it('has a README has a description when specified', () => {
    // GIVEN
    const project = new TestProject();

    // WHEN
    new Readme(project, { description: 'This is a test project.' });

    // THEN
    const output = synthSnapshot(project)['README.md'];
    expect(output).toEqual(
      `<!-- ~~ Generated by projen. To modify, edit .projenrc.js and run "npx projen". -->

# my-project

This is a test project.

`,
    );
  });
});

describe('README sections', () => {
  const headings = (project: Project) =>
    (synthSnapshot(project)['README.md'] as string)
      .split('\n')
      .filter((line) => line.startsWith('## '));

  it('keeps sections without an order in the order they were added', () => {
    const project = new TestProject();
    const readme = new Readme(project);

    readme.addSection('First', 'one');
    readme.addSection('Second', 'two');

    expect(headings(project)).toEqual(['## First', '## Second']);
  });

  it('orders sections by order, then the order they were added', () => {
    const project = new TestProject();
    const readme = new Readme(project);

    readme.addSection('Reference', 'r', { order: ReadmeOrder.REFERENCE });
    readme.addSection('Downstream', 'd');
    readme.addSection('Usage', 'u', { order: ReadmeOrder.USAGE });
    readme.addSection('Getting Started', 'g', {
      order: ReadmeOrder.INTRODUCTION,
    });
    readme.addSection('More Usage', 'm', { order: ReadmeOrder.USAGE });

    expect(headings(project)).toEqual([
      '## Getting Started',
      '## Usage',
      '## More Usage',
      '## Downstream',
      '## Reference',
    ]);
  });

  it('replaces a section with the same title in its place', () => {
    const project = new TestProject();
    const readme = new Readme(project);
    readme.addSection('First', 'one', { order: ReadmeOrder.INTRODUCTION });
    readme.addSection('Second', 'two');

    readme.addSection('First', 'replaced');

    const output: string = synthSnapshot(project)['README.md'];
    expect(output.match(/^## .*/gm)).toEqual(['## First', '## Second']);
    expect(output).toContain('## First\n\nreplaced');
    expect(output).not.toContain('one');
  });

  it('moves a replaced section when given an order', () => {
    const project = new TestProject();
    const readme = new Readme(project);
    readme.addSection('First', 'one');
    readme.addSection('Second', 'two');

    readme.addSection('First', 'one', { order: ReadmeOrder.REFERENCE });

    expect(headings(project)).toEqual(['## Second', '## First']);
  });

  it('removes a section', () => {
    const project = new TestProject();
    const readme = new Readme(project);
    readme.addSection('First', 'one');
    readme.addSection('Second', 'two');

    expect(readme.removeSection('First')).toBe(true);
    expect(readme.removeSection('Missing')).toBe(false);

    expect(headings(project)).toEqual(['## Second']);
  });

  it('finds a section by title', () => {
    const project = new TestProject();
    const readme = new Readme(project);
    readme.addSection('First', 'one');

    expect(readme.tryFindSection('First')?.options.body).toBe('one');
    expect(readme.tryFindSection('Missing')).toBeUndefined();
  });

  it('is found on its project', () => {
    const project = new TestProject();
    expect(Readme.of(project)).toBeUndefined();

    const readme = new Readme(project);

    expect(Readme.of(project)).toBe(readme);
  });
});

describe('getting started', () => {
  function nodeProject(options: Partial<NodeProjectOptions> = {}) {
    return new NodeProject({
      defaultReleaseBranch: 'main',
      name: 'my-project',
      ...options,
    });
  }

  it('lists the prerequisites before the commands', () => {
    expect(
      gettingStartedSection(nodeProject({ minNodeVersion: '22.0.0' })),
    ).toBe(
      'Prerequisites:\n* Node.js 22\n* Yarn 1 (classic)\n\n```sh\nyarn install\nnpx projen build\n```',
    );
  });

  it('installs with the package manager of a node project', () => {
    const project = nodeProject({ packageManager: NodePackageManager.PNPM });

    expect(gettingStartedSection(project)).toContain(
      '```sh\npnpm install\nnpx projen build\n```',
    );
  });

  it('shows the major of the given node version', () => {
    const project = nodeProject({
      minNodeVersion: '20.0.0',
      workflowNodeVersion: '24.x',
    });

    expect(gettingStartedSection(project, { nodeVersion: '24.x' })).toContain(
      '* Node.js 24\n',
    );
  });

  it('falls back to the minimum node version', () => {
    expect(
      gettingStartedSection(nodeProject({ minNodeVersion: '20.10.0' })),
    ).toContain('* Node.js 20\n');
  });

  it('falls back to a current LTS release without a node version', () => {
    expect(gettingStartedSection(nodeProject())).toContain(
      '* a current Node.js LTS release\n',
    );
  });

  it('falls back to a current LTS release for an LTS alias', () => {
    expect(
      gettingStartedSection(nodeProject(), { nodeVersion: 'lts/*' }),
    ).toContain('* a current Node.js LTS release\n');
  });

  it.each([
    [NodePackageManager.YARN, 'Yarn 1 (classic)'],
    [NodePackageManager.YARN_CLASSIC, 'Yarn 1 (classic)'],
    [NodePackageManager.YARN2, 'Yarn 3.6.0 (Berry)'],
    [NodePackageManager.YARN_BERRY, 'Yarn 3.6.0 (Berry)'],
    [NodePackageManager.NPM, 'npm'],
    [NodePackageManager.PNPM, 'pnpm 9.1.0'],
    [NodePackageManager.BUN, 'Bun'],
  ])('lists the %s package manager', (packageManager, label) => {
    const project = nodeProject({
      packageManager,
      pnpmVersion: '9.1.0',
      yarnBerryOptions: { version: '3.6.0' },
    });

    expect(gettingStartedSection(project)).toContain(`* ${label}\n`);
  });

  it('lists the extra prerequisites last', () => {
    expect(
      gettingStartedSection(nodeProject({ packageManager: NodePackageManager.NPM }), {
        prerequisites: ['Docker'],
      }),
    ).toContain('* npm\n* Docker\n\n');
  });

  it('installs with projen for other projects', () => {
    expect(gettingStartedSection(new TestProject())).toBe(
      'Prerequisites:\n* a current Node.js LTS release, to run projen\n\n```sh\nnpx projen install\nnpx projen build\n```',
    );
  });
});

describe('generated README', () => {
  it('marks the README as generated by projen', () => {
    const project = new NodeProject({
      defaultReleaseBranch: 'main',
      name: 'my-project',
    });
    new Readme(project);

    expect(synthSnapshot(project)['README.md']).toMatch(
      /^<!-- ~~ Generated by projen\. To modify, edit .+ and run "npx projen"\. -->\n\n# my-project\n/,
    );
  });

  it("replaces projen's sample README", () => {
    const project = new NodeProject({
      defaultReleaseBranch: 'main',
      name: 'my-project',
    });
    expect(project.components.some((c) => c instanceof SampleReadme)).toBe(
      true,
    );

    new Readme(project);

    expect(project.components.some((c) => c instanceof SampleReadme)).toBe(
      false,
    );
  });
});
